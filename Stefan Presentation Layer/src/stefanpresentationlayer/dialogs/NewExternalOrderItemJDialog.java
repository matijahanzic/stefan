    private void quantityFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_quantityFocusLost
        int qtyValue;

        try {
            qtyValue = Integer.parseInt(quantity.getText());
        } catch (NumberFormatException nfe) {
            return;
        }

        if (qtyValue <= 0) {
            JOptionPane.showMessageDialog(this.getParent(), "Upišite ispravnu vrijednost za količinu (vrijednost mora biti veća od 0)", "Greška", JOptionPane.WARNING_MESSAGE);
            return;
        }

        PresentationHelper ph = new PresentationHelper(this.design, qtyValue, null);
        this.finalPrice.setText(ph.getPricePerPart().toString());
    }//GEN-LAST:event_quantityFocusLost

