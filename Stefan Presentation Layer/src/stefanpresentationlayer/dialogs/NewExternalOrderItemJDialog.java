    private void confirmBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmBtnActionPerformed
        String errorMessage = null;

        String quantityText = quantity.getText();
        if (quantityText == null || quantityText.isEmpty())
            errorMessage = "Količina je obavezan podatak";

        String finalPriceText = finalPrice.getText();
        if (finalPriceText == null || finalPriceText.isEmpty()) {
            String msg = "Konačna cijena je obavezan podatak";
            if (errorMessage != null)
                errorMessage += "\n" + msg;
            else
                errorMessage = msg;
        }

        if (errorMessage == null) {
            String msg = "Količina mora biti cijeli broj veći od 0";
            try {
                quantityValue = Integer.parseInt(quantityText);
                if (quantityValue <= 0)
                    errorMessage = msg;
            } catch (NumberFormatException nfe) {
                errorMessage = msg;
            }

            msg = "Konačna cijena mora biti decimalni broj veći od 0";
            try {
                finalPriceValue = Double.parseDouble(finalPriceText);
                if (finalPriceValue <= 0.) {
                    if (errorMessage != null)
                        errorMessage += "\n" + msg;
                    else
                        errorMessage = msg;
                }
            } catch (NumberFormatException nfe) {
                if (errorMessage != null)
                    errorMessage += "\n" + msg;
                else
                    errorMessage = msg;
            }
        }

        if (errorMessage != null) {
            JOptionPane.showMessageDialog(this, errorMessage, "Greške", JOptionPane.WARNING_MESSAGE);
            return;
        }

        this.optionPaneExitCode = JOptionPane.OK_OPTION;
        this.dispose();
    }//GEN-LAST:event_confirmBtnActionPerformed

